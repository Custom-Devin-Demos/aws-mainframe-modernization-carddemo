#!/usr/bin/env python3
"""Converts the raw output of a GnuCOBOL run of CBACT03C into the canonical expected fixtures.

  to_canonical.py run   <run-dir> <expected-dir>
      <run-dir>/stdout (SYSOUT), stderr (CEE3ABD stub message), exit (process status) ->
        sysout.txt        SYSOUT exactly as displayed (50-byte record images keep trailing spaces)
      only when the run did not abend (an abend publishes no datasets):
        sysout.csv        line_no,line_text   (line_text right-trimmed)
        xref_listing.csv  xref_card_num,xref_cust_id,xref_acct_id:
                          one row per record the program READ, taken from the DISPLAY lines; each
                          record is displayed twice (1000-XREFFILE-GET-NEXT and the main loop), the
                          two images are checked to be identical. CVACT03Y slicing: card 1-16
                          (PIC X, right-trimmed), cust 17-25 and acct 26-36 (PIC 9, kept as is).
        run.properties    abended, abend_code, return_code
  to_canonical.py iostat <statuses-file> <driver-stdout> <expected-csv>
      io_status,line_text per input status (paragraph 9910-DISPLAY-IO-STATUS).
"""
import re
import sys

START = "START OF EXECUTION OF PROGRAM CBACT03C"
END = "END OF EXECUTION OF PROGRAM CBACT03C"


def escape(s):
    if any(c in s for c in ',"\n\r') or (s and (s[0] == " " or s[-1] == " ")):
        return '"' + s.replace('"', '""') + '"'
    return s


def write_csv(path, header, rows):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(",".join(header) + "\n")
        for r in rows:
            f.write(",".join(escape(str(v)) for v in r) + "\n")


def read_lines(path):
    with open(path, "rb") as f:
        data = f.read().decode("latin-1")
    lines = data.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def run(run_dir, out_dir):
    lines = read_lines(f"{run_dir}/stdout")
    with open(f"{run_dir}/stderr", encoding="latin-1") as f:
        stderr = f.read()
    with open(f"{run_dir}/exit") as f:
        exit_status = int(f.read().strip())
    m = re.search(r"CEE3ABD ABCODE=(\d+)", stderr)
    abended = m is not None

    with open(f"{out_dir}/sysout.txt", "w", encoding="latin-1", newline="") as f:
        f.writelines(l + "\n" for l in lines)
    if not abended:
        write_csv(f"{out_dir}/sysout.csv", ["line_no", "line_text"],
                  [(i + 1, l.rstrip(" ")) for i, l in enumerate(lines)])
        assert lines[0] == START and lines[-1] == END, "unexpected SYSOUT framing"
        body = lines[1:-1]
        assert len(body) % 2 == 0, "records are expected to be displayed twice"
        rows = []
        for i in range(0, len(body), 2):
            assert body[i] == body[i + 1], f"record displayed differently: {body[i]!r} {body[i + 1]!r}"
            rec = body[i].ljust(50)
            rows.append((rec[0:16].rstrip(" "), rec[16:25], rec[25:36]))
        write_csv(f"{out_dir}/xref_listing.csv", ["xref_card_num", "xref_cust_id", "xref_acct_id"], rows)

    with open(f"{out_dir}/run.properties", "w", encoding="ascii") as f:
        f.write("# Generated by tools/cobol/to_canonical.py from a GnuCOBOL run of app/cbl/CBACT03C.cbl\n")
        f.write(f"abended={'true' if abended else 'false'}\n")
        f.write(f"abend_code={int(m.group(1)) if abended else ''}\n")
        f.write(f"return_code={'' if abended else exit_status}\n")


def iostat(statuses_file, driver_stdout, out_csv):
    statuses = [l for l in read_lines(statuses_file) if l]
    lines = read_lines(driver_stdout)
    assert len(statuses) == len(lines), f"{len(statuses)} statuses vs {len(lines)} lines"
    write_csv(out_csv, ["io_status", "line_text"], list(zip(statuses, (l.rstrip(" ") for l in lines))))


if __name__ == "__main__":
    {"run": run, "iostat": iostat}[sys.argv[1]](*sys.argv[2:])
